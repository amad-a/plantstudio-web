#!/usr/bin/env python3
"""Generate src/model/params.js from the original Parameters.tab.

usage: python3 -I tools/gen-params.py <upstream PlantStudio checkout> src/model/params.js

Parameters.tab was the authors' own master table: Delphi's transfer code was
generated from it, and here the file reader, writer and parameter panel are.
"""
import csv, json, re, sys

upstream, out = sys.argv[1], sys.argv[2]

CONSTANTS = {
    'kGenderMale': 0, 'kGenderFemale': 1, 'kBud': 0, 'kPistils': 1, 'kStamens': 2,
    'kFirstPetals': 3, 'kSecondPetals': 4, 'kThirdPetals': 5, 'kFourthPetals': 6,
    'kFifthPetals': 7, 'kSepals': 8,
}
TYPES = {'1': 'float', '2': 'int', '3': 'color', '4': 'bool', '5': 'tdo', '6': 'enum', '7': 'header'}
ENUMS = {
    'kMeristemAndLeafArrangement': ['Alternate', 'Opposite'],
    'kLeafCompoundPinnateOrPalmate': ['Pinnate', 'Palmate'],
    'kLeafCompoundPinnateArrangement': ['Alternate', 'Opposite'],
    'kFlowerMaleBudOption': ['No bud', 'Single 3D object', 'Opening flower'],
    'kFlowerFemaleBudOption': ['No bud', 'Single 3D object', 'Opening flower'],
}

# Delphi is case-insensitive and the table is inconsistent ("ScaleAtFullSize"),
# so canonical spellings come from the field declarations.
source = open(f'{upstream}/for-olpc-python/uplant.py', encoding='latin1').read()
canonical = {name.lower(): name for name in re.findall(r'self\.(\w+) = ', source)}

def path_for(access):
    path = []
    for name, index in re.findall(r'(\w+)(?:\[(\w+)\])?', access):
        path.append(canonical.get(name.lower(), name))
        if index:
            path.append(CONSTANTS[index])
    return path

rows = list(csv.DictReader(open(f'{upstream}/converted_source/tab/Parameters.tab', encoding='latin1', newline=''), delimiter='\t'))
rows.sort(key=lambda r: (int(r['section order'] or 999), int(r['parameter order'] or 0)))

sections, params = [], []
for row in rows:
    kind = TYPES[row['fieldType'].split()[0]]
    if row['section'] not in sections:
        sections.append(row['section'])
    if kind == 'header':
        params.append({'section': row['section'], 'type': kind, 'name': row['name'], 'hint': row['IndexType']})
        continue
    param = {
        'section': row['section'],
        'also': [s.strip() for s in row['other sections this parameter is in'].split(',') if s.strip()],
        'id': row['FieldID'], 'name': row['name'], 'type': kind,
        'def': row['defaultValue'], 'path': path_for(row['accessString']),
        'unit': row['unitModel'].split(' ', 1)[-1] if row['unitModel'] else '',
        'hint': row['hint'],
    }
    if row['lowerBound'] != '':
        param['lower'] = float(row['lowerBound'])
    if row['upperBound'] != '':
        param['upper'] = float(row['upperBound'])
    if 'S curve' in row['IndexType']:
        param['scurve'] = True
    if param['id'] in ENUMS:
        param['choices'] = ENUMS[param['id']]
    params.append(param)

with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen-params.py from Parameters.tab. Do not edit.\n')
    f.write('export const SECTIONS = ' + json.dumps(sections, ensure_ascii=False) + ';\n')
    f.write('export const PARAMS = [\n')
    for param in params:
        f.write(json.dumps(param, ensure_ascii=False) + ',\n')
    f.write('];\n')
print(len(sections), 'sections', sum(p['type'] != 'header' for p in params), 'parameters')
